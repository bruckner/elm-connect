use std::path::PathBuf;
use std::process::ExitCode;

use clap::{Args, Parser, Subcommand};
use elm_connect_gen::diagnostics::Diagnostics;
use elm_connect_gen::naming::REPOSITORY_FILES;
use elm_connect_gen::{
    Bytes, Codec, EnumUnknown, Generated, Int64, ModuleName, Options, Spelling, Streaming,
    UnboundMethods,
};
use miette::Report;

/// What the top-level help says after the commands: where to start.
fn start_here() -> String {
    format!(
        "Start here:
  1. Generate Elm modules from the protos:
       elm-connect gen -I proto notes/v1/notes.proto --out generated
  2. Add the runtime: the generated code imports `Proto.*` and `Rpc.*` from the
     elm-connect runtime, read from a clone's `src/` as a source directory until
     it is published (`elm install bruckner/elm-connect` then).
  3. In CI, run `elm-connect check` with the same arguments; it exits 1 on drift.

`elm-connect guide` prints the guide to working on a project that uses it.
Docs: {REPOSITORY_FILES}docs"
    )
}

/// Generate Elm clients for protobuf APIs.
#[derive(Parser)]
#[command(version = elm_connect_gen::VERSION, after_help = start_here())]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Compile .proto files and generate Elm modules from them.
    ///
    /// Each module written is listed on stdout. Nothing under `--out` is
    /// deleted: a module these protos no longer give is named in a
    /// warning.
    #[command(after_long_help = GEN_EXAMPLES)]
    Gen(GenArgs),
    /// Check that the generated Elm modules are current; for CI.
    ///
    /// Generates as `gen` would, in memory, and compares with the modules
    /// under `--out`. Takes exactly `gen`'s arguments, `-I` included: each
    /// module's first line names its protos by their paths under the
    /// include directory. Exit status 0 when the modules are current, 1
    /// when one is missing, differs or is stale (generated by elm-connect
    /// from these protos, but no longer given by them), and 2 when it
    /// cannot tell (bad arguments, a proto that does not compile, an
    /// unreadable directory).
    #[command(after_long_help = CHECK_EXAMPLES)]
    Check(GenArgs),
    /// Print the guide to working on a project that uses elm-connect.
    ///
    /// The guide is Markdown, for an agent or a person: regenerating, checking before and after a change, reading
    /// a diagnostic and choosing its escape, and the application's
    /// `elm.json`. Its links point at the docs on GitHub.
    Guide,
}

/// What `gen --help` ends with.
const GEN_EXAMPLES: &str = "Examples:
  elm-connect gen -I proto notes/v1/notes.proto --out generated
  elm-connect gen -I proto notes/v1/notes.proto --out generated --rename notes.v1.Note:Memo
  elm-connect gen -I proto notes/v1/notes.proto --out generated --module-prefix Api";

/// What `check --help` ends with.
const CHECK_EXAMPLES: &str = "Examples:
  elm-connect check -I proto notes/v1/notes.proto --out generated
  elm-connect check -I proto notes/v1/notes.proto --out generated --rename notes.v1.Note:Memo
  elm-connect check -I proto notes/v1/notes.proto --out generated --module-prefix Api";

/// What to generate from and how: the arguments `gen` and `check` share.
#[derive(Args)]
struct GenArgs {
    /// The .proto files to generate from, relative to an include directory.
    #[arg(required = true)]
    files: Vec<PathBuf>,
    /// A directory to search for imports; repeatable. Defaults to `.`.
    #[arg(short = 'I', long = "proto-path", value_name = "DIR")]
    includes: Vec<PathBuf>,
    /// The directory of the Elm modules.
    ///
    /// `gen` writes them there, and `check` compares them with what it
    /// would write.
    #[arg(short, long, value_name = "DIR")]
    out: PathBuf,
    /// How to hold 64-bit integers: `string` (exact) or `int`.
    ///
    /// `int` is Elm's `Int`, exact within ±(2^53 − 1); larger values fail
    /// to decode. A field's `jstype` option overrides it.
    #[arg(long, value_name = "string|int", default_value = "string")]
    int64: Int64,
    /// How to hold `bytes` fields: `string` (base64) or `bytes`.
    ///
    /// `string` is the base64 text as received. `bytes` is elm/bytes'
    /// `Bytes`; Elm's `==` finds any two `Bytes` equal, so records holding
    /// them compare equal whatever the bytes.
    #[arg(long, value_name = "string|bytes", default_value = "string")]
    bytes: Bytes,
    /// What a method without a `google.api.http` rule gets: `implicit` or
    /// `error`.
    ///
    /// `implicit`: a call the runtime sends over the implicit route,
    /// `POST /<package>.<Service>/<Method>`. `error`: a diagnostic.
    #[arg(long, value_name = "implicit|error", default_value = "implicit")]
    unbound_methods: UnboundMethods,
    /// What a streaming method gets: `error` or `skip`.
    ///
    /// A client, server or bidirectional streaming method. `error`: a
    /// diagnostic. `skip`: left out of its service's module, with a
    /// warning; the rest is generated.
    #[arg(long, value_name = "error|skip", default_value = "error")]
    streaming: Streaming,
    /// What an unknown enum value name decodes as: `fail` or `zero`.
    ///
    /// `fail`: the decode fails. `zero`: the name reads as the zero value,
    /// as an unknown number always does. It applies to every enum the
    /// invocation generates. Packages that refer to none of each other's
    /// types can take different values in separate invocations, each with
    /// its own `--out`.
    #[arg(long, value_name = "fail|zero", default_value = "fail")]
    enum_unknown: EnumUnknown,
    /// Which codecs messages get: `json`, `binary` or `both`.
    ///
    /// `json`: proto3 JSON, for Connect's JSON codec and transcoding.
    /// `binary`: protobuf binary alone, for Connect's proto codec. `both`:
    /// the binary codecs beside the JSON ones.
    #[arg(long, value_name = "json|binary|both", default_value = "json")]
    codec: Codec,
    /// An Elm name for a proto element, such as `notes.v1.Note:Memo`.
    ///
    /// The value is `<proto full name>:<Elm name>`, and the Elm name
    /// replaces the one the naming rules derive; repeatable. The proto
    /// name is a package, service, method, message, enum, field, oneof or
    /// enum value.
    #[arg(long, value_name = "PROTO:ELM", value_parser = rename_entry)]
    rename: Vec<String>,
    /// The module every generated module goes inside, such as `Api`.
    ///
    /// With `Api`, `notes.v1` becomes `Api.Notes.V1`, in
    /// `Api/Notes/V1.elm`. The runtime's modules are never prefixed.
    #[arg(long, value_name = "MODULE", value_parser = module_prefix)]
    module_prefix: Option<ModuleName>,
    /// Also generate the imported files the given ones refer to.
    ///
    /// Generates every imported file that declares a message or enum the
    /// given files' packages refer to, transitively, each imported package
    /// from those files alone; without it, a reference to a
    /// package none of the given files declares is an error. A file
    /// imported only for its options (`google/api/annotations.proto`,
    /// `google/api/client.proto`) is not generated, nor are
    /// `google/protobuf` files, which map to the runtime.
    #[arg(long)]
    include_imports: bool,
}

impl GenArgs {
    /// The generator's options the flags set.
    fn options(&self) -> miette::Result<Options> {
        let mut options = Options::default();
        options.int64 = self.int64;
        options.bytes = self.bytes;
        options.unbound_methods = self.unbound_methods;
        options.streaming = self.streaming;
        options.enum_unknown = self.enum_unknown;
        options.codec = self.codec;
        options.module_prefix = self.module_prefix.clone();
        options.spelling = Spelling::Flags;
        let mut problems = Diagnostics::new();
        for entry in &self.rename {
            if let Err(problem) = options.add_rename(entry) {
                problems.push(problem);
            }
        }
        if !problems.is_empty() {
            return Err(Report::new(problems));
        }
        Ok(options)
    }

    /// The `elm-connect gen` command with these files, include paths,
    /// output directory and `--include-imports`, but no options.
    fn gen_command(&self) -> String {
        let word = |path: &PathBuf| elm_connect::shell_word(&path.display().to_string());
        let mut command = String::from("elm-connect gen");
        for include in &self.includes {
            command.push_str(&format!(" -I {}", word(include)));
        }
        for file in &self.files {
            command.push_str(&format!(" {}", word(file)));
        }
        command.push_str(&format!(" --out {}", word(&self.out)));
        if self.include_imports {
            command.push_str(" --include-imports");
        }
        command
    }

    /// Generates as the flags say, printing any warnings to stderr.
    fn generate(&self) -> miette::Result<Generated> {
        let generated = elm_connect::generate(
            &self.files,
            &self.includes,
            self.include_imports,
            &self.options()?,
        )?;
        if !generated.warnings.is_empty() {
            eprintln!("{:?}", Report::new(generated.warnings.clone()));
        }
        Ok(generated)
    }
}

/// A `--rename` value, checked for its `<proto full name>:<Elm name>`
/// form.
fn rename_entry(value: &str) -> Result<String, String> {
    elm_connect_gen::parse_rename(value)
        .map(|_| value.to_owned())
        .map_err(|problem| format!("{} {}", problem.message(), problem.help_text()))
}

/// A `--module-prefix` value: dot-separated Elm module segments.
fn module_prefix(value: &str) -> Result<ModuleName, String> {
    elm_connect_gen::parse_module_prefix(value)
        .map_err(|problem| format!("{} {}", problem.message(), problem.help_text()))
}

/// `check`'s exit status when it cannot tell whether the tree is current,
/// apart from drift's 1; clap exits with it on bad arguments too.
const CHECK_ERROR: u8 = 2;

/// The guide `elm-connect guide` prints. `docs/guide.md` is the
/// source; this copy sits in the crate because a published crate holds
/// only its own files, and a test keeps the two equal.
const GUIDE: &str = include_str!("../guide.md");

/// [`GUIDE`] with its relative links made absolute, since a terminal has
/// no page to resolve them against: `generator.md#options` and
/// `../AGENTS.md` become links to those files on GitHub.
fn guide() -> String {
    let docs = format!("{REPOSITORY_FILES}docs/");
    GUIDE
        .split("](")
        .enumerate()
        .map(|(index, part)| {
            if index == 0 || part.starts_with("https://") || part.starts_with("http://") {
                part.to_owned()
            } else if let Some(from_root) = part.strip_prefix("../") {
                format!("{REPOSITORY_FILES}{from_root}")
            } else {
                format!("{docs}{part}")
            }
        })
        .collect::<Vec<_>>()
        .join("](")
}

/// The line under a failure's diagnostics, for a reader who has nothing
/// but the binary.
fn diagnostics_pointer() -> String {
    format!(
        "Codes and their escapes: {REPOSITORY_FILES}docs/diagnostics.md; `elm-connect guide` \
         says how to choose one."
    )
}

fn main() -> ExitCode {
    let (result, error_status) = match Cli::parse().command {
        Command::Gen(args) => (generate(&args), ExitCode::FAILURE),
        Command::Check(args) => (check(&args), ExitCode::from(CHECK_ERROR)),
        Command::Guide => {
            print!("{}", guide());
            return ExitCode::SUCCESS;
        }
    };
    result.unwrap_or_else(|report| {
        // Problems render each under its own `Error:`, below a header
        // counting them, with a pointer to the catalogue of their codes;
        // any other failure is one error, named here.
        if report.downcast_ref::<Diagnostics>().is_some() {
            eprintln!("{report:?}");
            eprintln!("{}", diagnostics_pointer());
        } else {
            eprintln!("Error: {report:?}");
        }
        error_status
    })
}

/// `gen`: writes the modules, lists them on stdout, and says on stderr
/// how many were written and which stale files remain beside them.
fn generate(args: &GenArgs) -> miette::Result<ExitCode> {
    let generated = args.generate()?;
    let written = elm_connect::write(&generated.files, &args.out)?;
    for path in &written {
        println!("{}", path.display());
    }
    let out = args.out.display();
    for path in elm_connect::stale(&generated.files, &args.out)? {
        eprintln!(
            "warning: {out}/{path} was generated by elm-connect from these protos, but they no \
             longer give it; delete it if nothing else generates it"
        );
    }
    let modules = if written.len() == 1 {
        "module"
    } else {
        "modules"
    };
    eprintln!("Wrote {} {modules} under {out}.", written.len());
    Ok(ExitCode::SUCCESS)
}

/// `check`: prints what drifted, exiting 1 if anything did.
fn check(args: &GenArgs) -> miette::Result<ExitCode> {
    let generated = args.generate()?;
    let check = elm_connect::check(&generated.files, &args.out)?;
    print!("{}", check.render(&args.gen_command()));
    Ok(if check.is_current() {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::CommandFactory;

    /// `gen`'s arguments, parsed from `a.proto --out out` and `args`.
    fn gen_args(args: &[&str]) -> Result<GenArgs, clap::Error> {
        let base = ["elm-connect", "gen", "a.proto", "--out", "out"];
        match Cli::try_parse_from(base.iter().chain(args))?.command {
            Command::Gen(args) => Ok(args),
            Command::Check(_) | Command::Guide => unreachable!("parsed as gen"),
        }
    }

    #[test]
    fn check_takes_the_arguments_of_gen() {
        let args = [
            "elm-connect",
            "check",
            "a.proto",
            "b.proto",
            "-I",
            "protos",
            "--out",
            "generated",
            "--int64",
            "int",
            "--bytes",
            "bytes",
            "--unbound-methods",
            "error",
            "--streaming",
            "skip",
            "--enum-unknown",
            "zero",
            "--rename",
            "notes.v1.Note:Memo",
            "--module-prefix",
            "Api",
            "--include-imports",
        ];
        let Command::Check(args) = Cli::try_parse_from(args).expect("parses").command else {
            panic!("parsed as check");
        };
        assert_eq!(
            args.files,
            [PathBuf::from("a.proto"), PathBuf::from("b.proto")]
        );
        assert_eq!(args.includes, [PathBuf::from("protos")]);
        assert_eq!(args.out, PathBuf::from("generated"));
        let options = args.options().expect("valid options");
        assert_eq!(options.int64, Int64::Int);
        assert_eq!(options.bytes, Bytes::Bytes);
        assert_eq!(options.unbound_methods, UnboundMethods::Error);
        assert_eq!(options.streaming, Streaming::Skip);
        assert_eq!(options.enum_unknown, EnumUnknown::Zero);
        assert_eq!(options.spelling, Spelling::Flags);
        assert!(args.include_imports);
        assert!(Cli::try_parse_from(["elm-connect", "check", "a.proto"]).is_err());
    }

    fn int64(args: &[&str]) -> Result<Int64, clap::Error> {
        gen_args(args).map(|args| args.int64)
    }

    fn unbound_methods(args: &[&str]) -> Result<UnboundMethods, clap::Error> {
        gen_args(args).map(|args| args.unbound_methods)
    }

    #[test]
    fn unbound_methods_default_to_implicit_and_take_error() {
        assert_eq!(
            unbound_methods(&[]).expect("parses"),
            UnboundMethods::Implicit
        );
        assert_eq!(
            unbound_methods(&["--unbound-methods", "error"]).expect("parses"),
            UnboundMethods::Error
        );
        assert!(unbound_methods(&["--unbound-methods", "drop"]).is_err());
    }

    fn streaming(args: &[&str]) -> Result<Streaming, clap::Error> {
        gen_args(args).map(|args| args.streaming)
    }

    #[test]
    fn streaming_defaults_to_error_and_takes_skip() {
        assert_eq!(streaming(&[]).expect("parses"), Streaming::Error);
        assert_eq!(
            streaming(&["--streaming", "skip"]).expect("parses"),
            Streaming::Skip
        );
        assert!(streaming(&["--streaming", "drop"]).is_err());
    }

    fn enum_unknown(args: &[&str]) -> Result<EnumUnknown, clap::Error> {
        gen_args(args).map(|args| args.enum_unknown)
    }

    #[test]
    fn enum_unknown_defaults_to_fail_and_takes_zero() {
        assert_eq!(enum_unknown(&[]).expect("parses"), EnumUnknown::Fail);
        assert_eq!(
            enum_unknown(&["--enum-unknown", "zero"]).expect("parses"),
            EnumUnknown::Zero
        );
        assert!(enum_unknown(&["--enum-unknown", "variant"]).is_err());
    }

    fn rename(args: &[&str]) -> Result<Vec<String>, clap::Error> {
        gen_args(args).map(|args| args.rename)
    }

    #[test]
    fn rename_repeats_and_needs_a_colon() {
        assert_eq!(rename(&[]).expect("parses"), Vec::<String>::new());
        assert_eq!(
            rename(&[
                "--rename",
                "notes.v1.Note:Memo",
                "--rename",
                "notes.v1.Note.title:heading"
            ])
            .expect("parses"),
            ["notes.v1.Note:Memo", "notes.v1.Note.title:heading"]
        );
        assert!(rename(&["--rename", "notes.v1.Note"]).is_err());
        assert!(rename(&["--rename", "notes.v1.Note:"]).is_err());
        assert!(int64(&["--int64", "int", "--int64", "string"]).is_err());
    }

    #[test]
    fn a_proto_renamed_twice_is_a_problem_in_the_options() {
        let args = gen_args(&["--rename", "a.B:C", "--rename", "a.B:D"]).expect("parses");
        let report = args.options().expect_err("a.B is renamed twice");
        let handler =
            miette::GraphicalReportHandler::new_themed(miette::GraphicalTheme::unicode_nocolor());
        let mut rendered = String::new();
        handler
            .render_report(&mut rendered, report.as_ref())
            .expect("rendering into a String cannot fail");
        assert!(
            rendered.contains("elm-connect found a problem in the options"),
            "{rendered}"
        );
        assert!(
            rendered.contains("Error: options::duplicate_option"),
            "{rendered}"
        );
        assert!(
            rendered.contains("rename `a.B` more than once"),
            "{rendered}"
        );
    }

    fn module_prefix(args: &[&str]) -> Result<Option<String>, clap::Error> {
        gen_args(args).map(|args| args.module_prefix.map(|module| module.to_string()))
    }

    #[test]
    fn module_prefix_takes_elm_module_segments_once() {
        assert_eq!(module_prefix(&[]).expect("parses"), None);
        assert_eq!(
            module_prefix(&["--module-prefix", "Api.Notes"]).expect("parses"),
            Some("Api.Notes".to_owned())
        );
        for invalid in ["", "api.Notes", "Api.", "Api-Notes"] {
            let error = module_prefix(&["--module-prefix", invalid]).unwrap_err();
            assert!(
                error
                    .to_string()
                    .contains("A module prefix is dot-separated Elm module segments"),
                "{invalid}: {error}"
            );
        }
        assert!(module_prefix(&["--module-prefix", "Api", "--module-prefix", "Web"]).is_err());
    }

    fn include_imports(args: &[&str]) -> Result<bool, clap::Error> {
        gen_args(args).map(|args| args.include_imports)
    }

    #[test]
    fn include_imports_defaults_to_off_and_takes_no_value() {
        assert!(!include_imports(&[]).expect("parses"));
        assert!(include_imports(&["--include-imports"]).expect("parses"));
        assert!(include_imports(&["--include-imports=true"]).is_err());
    }

    #[test]
    fn int64_defaults_to_string_and_takes_int() {
        assert_eq!(int64(&[]).expect("parses"), Int64::String);
        assert_eq!(int64(&["--int64", "int"]).expect("parses"), Int64::Int);
        assert!(int64(&["--int64", "long"]).is_err());
    }

    fn bytes(args: &[&str]) -> Result<Bytes, clap::Error> {
        gen_args(args).map(|args| args.bytes)
    }

    #[test]
    fn bytes_defaults_to_string_and_takes_bytes() {
        assert_eq!(bytes(&[]).expect("parses"), Bytes::String);
        assert_eq!(bytes(&["--bytes", "bytes"]).expect("parses"), Bytes::Bytes);
        assert!(bytes(&["--bytes", "base64"]).is_err());
        assert!(bytes(&["--bytes", "bytes", "--bytes", "string"]).is_err());
    }

    #[test]
    fn the_guide_is_a_copy_of_its_source() {
        // In the repository, `guide.md` must equal its source; a published
        // crate has no `docs/`, and nothing to compare.
        let source = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../docs/guide.md");
        let Ok(source) = std::fs::read_to_string(source) else {
            return;
        };
        assert!(
            source == GUIDE,
            "crates/elm-connect/guide.md differs from docs/guide.md, its source: \
             copy docs/guide.md over it"
        );
    }

    #[test]
    fn the_guide_prints_its_links_absolute() {
        let printed = guide();
        assert!(printed.starts_with("# Using elm-connect"));
        for link in printed.split("](").skip(1) {
            assert!(
                link.starts_with(REPOSITORY_FILES),
                "a link is not absolute: {link}"
            );
        }
        let tagged = format!(
            "https://github.com/bruckner/elm-connect/blob/{}/",
            elm_connect_gen::VERSION
        );
        for path in [
            "AGENTS.md",
            "docs/generator.md#options",
            "docs/diagnostics.md",
        ] {
            let expected = format!("]({tagged}{path})");
            assert!(printed.contains(&expected), "{expected}");
        }
        assert!(Cli::try_parse_from(["elm-connect", "guide"]).is_ok());
    }

    #[test]
    fn the_help_says_where_to_start() {
        let help = Cli::command().render_long_help().to_string();
        assert!(help.contains("guide"), "{help}");
        assert!(help.contains("elm-connect gen -I proto"), "{help}");
        assert!(help.contains("elm-connect check"), "{help}");
    }
}
