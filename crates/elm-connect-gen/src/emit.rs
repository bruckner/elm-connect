//! The emitter: one IR [`Package`] to one Elm [`Module`] of record types
//! and their proto3 JSON codecs (design §2 layer 1, §3).
//!
//! Invariant: every name comes from the IR, every layout from the printer.
//! The emitter chooses which declarations exist and what their bodies say;
//! the Elm names of types, fields and codecs come from [`crate::ir`] (which
//! takes them from [`crate::naming`]), and the text is
//! [`crate::elm::print`]'s. The only names written here are those of the
//! libraries generated code calls: elm/json and the runtime package.
//!
//! The rules the emitter applies today:
//!
//! - A module opens with a generated-file notice, imports exactly the
//!   modules its code refers to, and holds three sections in order: types,
//!   encoders, decoders.
//! - A message is a record type alias, an encoder
//!   (`Foo -> Json.Encode.Value`) and a decoder (`Json.Decode.Decoder Foo`).
//! - Encoders emit every field, default values included. proto3 JSON lets
//!   a writer omit or include them; always including them keeps the
//!   encoder one expression per field. This is the current rule, not yet
//!   reviewed (design §3.4).
//! - Decoders are a pipeline of `Connect.Json.field` steps from
//!   `Json.Decode.succeed`, so they read the same at any field count
//!   (design §8). A missing or `null` field reads as its proto3 zero value.
//!
//! Only singular scalar fields are emitted so far. Every other construct
//! is reported as [`Code::Unimplemented`](crate::diagnostics::Code) through
//! [`crate::diagnostics`], never a panic, so a user meets an ordinary
//! diagnostic until its emitter lands.

mod message;
mod scalar;

use std::collections::BTreeSet;

use crate::VERSION;
use crate::diagnostics::{Diagnostics, Problem};
use crate::elm::ast::{Decl, Exposing, Expr, Import, Module, ModuleName, Type};
use crate::elm::build::{qualified, ty_qualified};
use crate::ir::{Cardinality, Field, Message, Package, ScalarKind, TypeRef};

/// elm/json's decoders.
const JSON_DECODE: &str = "Json.Decode";
/// elm/json's encoders.
const JSON_ENCODE: &str = "Json.Encode";
/// The runtime package's proto3 JSON helpers.
const CONNECT_JSON: &str = "Connect.Json";

/// How to generate. Nothing is configurable yet; the options design §6
/// lists arrive with the features they control.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
#[non_exhaustive]
pub struct Options {}

/// The Elm module for `package`, or every construct in it that has no
/// emitter yet.
pub fn emit(package: &Package, _options: &Options) -> Result<Module, Diagnostics> {
    let mut emitter = Emitter {
        imports: BTreeSet::new(),
        diagnostics: Diagnostics::new(),
    };
    let decls = emitter.package(package);
    if !emitter.diagnostics.is_empty() {
        return Err(emitter.diagnostics);
    }
    Ok(Module {
        header: Some(format!(
            "Generated by elm-connect {VERSION} from {}. Do not edit; regenerate instead.",
            package.files.join(", ")
        )),
        name: ModuleName::new(package.module.to_string()),
        doc: None,
        exposing: Exposing::All,
        imports: emitter
            .imports
            .into_iter()
            .map(|module| Import {
                module: ModuleName::new(module),
                alias: None,
                exposing: None,
            })
            .collect(),
        decls,
    })
}

/// The state of emitting one module: the library modules its code refers
/// to so far, and the problems found.
struct Emitter {
    imports: BTreeSet<&'static str>,
    diagnostics: Diagnostics,
}

/// A field's values as the emitter supports them: what [`Emitter::field`]
/// classifies an IR field into once, so that the type, the encoder and
/// the decoder of the field match on a closed set and report nothing.
#[derive(Clone, Copy, Debug)]
enum FieldShape {
    /// A singular scalar: the zero value when absent.
    Scalar(ScalarKind),
}

impl Emitter {
    /// The declarations of `package`, by section.
    fn package(&mut self, package: &Package) -> Vec<Decl> {
        for enumeration in &package.enums {
            self.unimplemented(&enumeration.proto_full_name, "an enum");
        }
        let messages: Vec<_> = package
            .messages
            .iter()
            .filter_map(|message| self.message_shape(message))
            .collect();
        if messages.is_empty() {
            return Vec::new();
        }
        let mut types = vec![Decl::Comment("TYPES".into())];
        let mut encoders = vec![Decl::Comment("ENCODERS".into())];
        let mut decoders = vec![Decl::Comment("DECODERS".into())];
        for (message, fields) in &messages {
            types.push(self.message_alias(message, fields));
            encoders.push(self.message_encoder(message, fields));
            decoders.push(self.message_decoder(message, fields));
        }
        types.into_iter().chain(encoders).chain(decoders).collect()
    }

    /// `message` with the shape of each of its fields, or `None` once every
    /// unsupported construct in it is reported.
    fn message_shape<'m>(
        &mut self,
        message: &'m Message,
    ) -> Option<(&'m Message, Vec<(&'m Field, FieldShape)>)> {
        let before = self.diagnostics.len();
        if message.recursive {
            self.unimplemented(&message.proto_full_name, "a recursive message");
        }
        for oneof in &message.oneofs {
            self.unimplemented(
                &format!("{}.{}", message.proto_full_name, oneof.proto_name),
                "a oneof",
            );
        }
        let fields: Vec<_> = message
            .fields
            .iter()
            .filter_map(|field| Some((field, self.field(message, field)?)))
            .collect();
        (self.diagnostics.len() == before).then_some((message, fields))
    }

    /// The shape of `field`, or `None` once it is reported.
    fn field(&mut self, message: &Message, field: &Field) -> Option<FieldShape> {
        let construct = match (field.cardinality, &field.ty) {
            (Cardinality::Singular, TypeRef::Scalar(kind)) => {
                return Some(FieldShape::Scalar(*kind));
            }
            (Cardinality::Optional, _) => "a proto3 `optional` field",
            (Cardinality::Repeated, _) => "a repeated field",
            (Cardinality::Map(_), _) => "a map field",
            (Cardinality::Singular, TypeRef::Message(_)) => "a message-typed field",
            (Cardinality::Singular, TypeRef::Enum(_)) => "an enum-typed field",
            (Cardinality::Singular, TypeRef::WellKnown(_)) => "a field of a well-known type",
        };
        self.unimplemented(
            &format!("{}.{}", message.proto_full_name, field.proto_name),
            construct,
        );
        None
    }

    /// The Elm type of a field.
    fn field_type(&mut self, shape: FieldShape) -> Type {
        match shape {
            FieldShape::Scalar(kind) => scalar::elm_type(kind),
        }
    }

    /// The encoder of a field's value: a function from it to
    /// `Json.Encode.Value`.
    fn field_encoder(&mut self, shape: FieldShape) -> Expr {
        match shape {
            FieldShape::Scalar(kind) => self.reference(scalar::encoder(kind)),
        }
    }

    /// The decoder of a field's value, and the value an absent field reads
    /// as.
    fn field_decoder(&mut self, shape: FieldShape) -> (Expr, Expr) {
        match shape {
            FieldShape::Scalar(kind) => (
                self.reference(scalar::decoder(kind)),
                scalar::zero_value(kind),
            ),
        }
    }

    /// A reference to `name` in the library module `module`, which the
    /// module then imports.
    fn reference(&mut self, (module, name): (&'static str, &str)) -> Expr {
        self.imports.insert(module);
        qualified(module, name)
    }

    /// The library type `module.name args`, which the module then imports.
    fn library_type(
        &mut self,
        module: &'static str,
        name: &str,
        args: impl IntoIterator<Item = Type>,
    ) -> Type {
        self.imports.insert(module);
        ty_qualified(module, name, args)
    }

    fn unimplemented(&mut self, element: &str, construct: &str) {
        self.diagnostics
            .push(Problem::unimplemented(element, construct));
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::diagnostics::Code;
    use crate::ir::{ModuleName as IrModule, Oneof, TypeName};

    fn package(messages: Vec<Message>) -> Package {
        Package {
            proto_name: "t.v1".into(),
            module: IrModule::new(vec!["T".into(), "V1".into()]).expect("valid"),
            files: vec!["a.proto".into(), "b.proto".into()],
            messages,
            enums: Vec::new(),
        }
    }

    fn message(name: &str, fields: Vec<Field>) -> Message {
        Message {
            proto_full_name: format!("t.v1.{name}"),
            elm_name: name.into(),
            fields,
            oneofs: Vec::new(),
            recursive: false,
        }
    }

    fn field(name: &str, cardinality: Cardinality, ty: TypeRef) -> Field {
        Field {
            proto_name: name.into(),
            json_name: name.into(),
            number: 1,
            elm_name: name.into(),
            cardinality,
            ty,
        }
    }

    fn problems(package: &Package) -> Vec<(Code, String)> {
        let diagnostics = emit(package, &Options::default()).expect_err("unsupported");
        diagnostics
            .iter()
            .map(|p| (p.code(), p.message().to_owned()))
            .collect()
    }

    #[test]
    fn header_names_the_package_files() {
        let module = emit(&package(Vec::new()), &Options::default()).expect("emits");
        assert_eq!(
            module.header.as_deref(),
            Some(&*format!(
                "Generated by elm-connect {VERSION} from a.proto, b.proto. Do not edit; \
                 regenerate instead."
            ))
        );
        assert_eq!(module.name.as_str(), "T.V1");
    }

    #[test]
    fn imports_only_what_the_code_uses() {
        let only_ints = package(vec![message(
            "A",
            vec![field(
                "n",
                Cardinality::Singular,
                TypeRef::Scalar(ScalarKind::Int32),
            )],
        )]);
        let module = emit(&only_ints, &Options::default()).expect("emits");
        let imports: Vec<&str> = module.imports.iter().map(|i| i.module.as_str()).collect();
        assert_eq!(imports, ["Connect.Json", "Json.Decode", "Json.Encode"]);

        let empty = package(vec![message("E", Vec::new())]);
        let module = emit(&empty, &Options::default()).expect("emits");
        let imports: Vec<&str> = module.imports.iter().map(|i| i.module.as_str()).collect();
        assert_eq!(imports, ["Json.Decode", "Json.Encode"]);
    }

    #[test]
    fn unsupported_constructs_are_diagnostics() {
        let other = TypeName {
            module: IrModule::new(vec!["T".into(), "V1".into()]).expect("valid"),
            name: "A".into(),
        };
        let string = TypeRef::Scalar(ScalarKind::String);
        let mut recursive = message("R", Vec::new());
        recursive.recursive = true;
        let mut with_oneof = message("O", Vec::new());
        with_oneof.oneofs.push(Oneof {
            proto_name: "kind".into(),
            elm_field_name: "kind".into(),
            elm_type_name: "OKind".into(),
            unset_ctor: "OKindUnset".into(),
            variants: Vec::new(),
        });
        let fields = message(
            "F",
            vec![
                field("ok", Cardinality::Singular, string.clone()),
                field("opt", Cardinality::Optional, string.clone()),
                field("rep", Cardinality::Repeated, string.clone()),
                field(
                    "msg",
                    Cardinality::Singular,
                    TypeRef::Message(other.clone()),
                ),
                field("en", Cardinality::Singular, TypeRef::Enum(other)),
            ],
        );
        let problems = problems(&package(vec![recursive, with_oneof, fields]));
        let messages: Vec<&str> = problems.iter().map(|(_, m)| m.as_str()).collect();
        assert!(
            problems
                .iter()
                .all(|(code, _)| *code == Code::Unimplemented)
        );
        assert_eq!(
            messages,
            [
                "`t.v1.R` is a recursive message, which elm-connect cannot generate yet.",
                "`t.v1.O.kind` is a oneof, which elm-connect cannot generate yet.",
                "`t.v1.F.opt` is a proto3 `optional` field, which elm-connect cannot generate yet.",
                "`t.v1.F.rep` is a repeated field, which elm-connect cannot generate yet.",
                "`t.v1.F.msg` is a message-typed field, which elm-connect cannot generate yet.",
                "`t.v1.F.en` is an enum-typed field, which elm-connect cannot generate yet.",
            ]
        );
    }
}
