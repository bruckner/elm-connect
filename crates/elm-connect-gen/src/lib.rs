/// The version of the generator, stamped into everything it emits.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// The `Proto.Version` value every generated module names, so that the
/// compiler refuses a runtime package from another release (design §8):
/// `v{major}_{minor}` of [`VERSION`], `v0_1` for 0.1.x.
pub const SENTINEL: &str = concat!(
    "v",
    env!("CARGO_PKG_VERSION_MAJOR"),
    "_",
    env!("CARGO_PKG_VERSION_MINOR")
);

/// What the committed expected output of the conformance corpus and the
/// route replay holds in place of [`VERSION`] on its header line: the
/// major and minor version with `X` for the patch, `0.1.X` for 0.1.x, so a
/// patch release leaves those files alone, and a minor release changes it
/// with [`SENTINEL`].
pub const HEADER_VERSION_PLACEHOLDER: &str = concat!(
    env!("CARGO_PKG_VERSION_MAJOR"),
    ".",
    env!("CARGO_PKG_VERSION_MINOR"),
    ".X"
);

/// The start of the line comment that opens every generated module, after
/// `-- `: the generator's [`VERSION`] follows, then the files it read.
pub const HEADER_PREFIX: &str = "Generated by elm-connect ";

/// The start of the line comment under that one, after `-- `: the options
/// the module was generated with follow, as [`Options::recorded`] gives
/// them, joined by `, `, or [`DEFAULT_OPTIONS`] when every option is at
/// its default.
pub const OPTIONS_PREFIX: &str = "Options: ";

/// What the options line holds after [`OPTIONS_PREFIX`] when every option
/// is at its default.
pub const DEFAULT_OPTIONS: &str = "defaults";

/// One generated Elm source file.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedFile {
    /// The path relative to the output directory, from the module name:
    /// `Notes/V1.elm` for `Notes.V1`. Always `/`-separated.
    pub path: String,
    /// The Elm source, in elm-format's layout.
    pub content: String,
}

/// What a successful run gives: the files, and what the run warned about.
#[derive(Clone, Debug)]
pub struct Generated {
    /// One file per module, sorted by path.
    pub files: Vec<GeneratedFile>,
    /// The warnings, in the order found: what the options left out, such
    /// as the streaming methods `streaming=skip` skips. Empty under the
    /// default options. Rendering them is the caller's business; both
    /// binaries print them to stderr.
    pub warnings: Diagnostics,
}

/// Generates one Elm module per proto package declared by the files in
/// `generate` (names as `pool` knows them), each in full from every file of
/// `pool` that declares it, one per message and enum of each holding its
/// descriptor, and one per service of each that has a method, sorted by
/// path. Only packages with a file in `generate` are generated,
/// as protoc plugins do: a reference to any other package (bar
/// `google.protobuf`, mapped to the runtime) is `generate::not_generated`,
/// whose help names the ways to request it (design §3.1). A package of
/// services alone still gets a package module, holding its registry. A
/// service without methods, declared so or left so by `streaming=skip`,
/// gets no module: Elm rejects a module that declares nothing.
///
/// On any error, returns every error found instead: those of building
/// the IR, or else the methods `options` reject, or else those of emitting
/// every package. Warnings come back only with the files.
pub fn generate(
    pool: &DescriptorPool,
    generate: &[&str],
    options: &Options,
) -> Result<Generated, Diagnostics> {
    generate_with_imports(pool, generate, &[], options)
}

/// [`generate`], and also the packages of the files in `imports`, each
/// from those files alone unless a file in `generate` declares it too
/// ([`ir::build_with_imports`]): what the CLI's `--include-imports`
/// generates.
pub fn generate_with_imports(
    pool: &DescriptorPool,
    generate: &[&str],
    imports: &[&str],
    options: &Options,
) -> Result<Generated, Diagnostics> {
    let ir::Built { packages, warnings } =
        ir::build_with_imports(pool, generate, imports, options)?;
    if options.unbound_methods == UnboundMethods::Error {
        let unbound = ir::unbound_methods(pool, &packages, options.spelling);
        if !unbound.is_empty() {
            return Err(unbound);
        }
    }
    let mut files = Vec::new();
    let mut diagnostics = Diagnostics::new();
    for package in &packages {
        match emit::emit(package, options) {
            Ok(module) => {
                files.push(file(&module));
                for descriptors in emit::emit_descriptor_modules(package, options) {
                    files.push(file(&descriptors));
                }
                for service in package.services.iter().filter(|s| !s.methods.is_empty()) {
                    files.push(file(&emit::emit_service(package, service, options)));
                }
            }
            Err(reserved) => {
                for name in &reserved {
                    let site = ir::name_site(pool, &name.element, name.label());
                    diagnostics.push(name.problem(site));
                }
            }
        }
    }
    if !diagnostics.is_empty() {
        return Err(diagnostics);
    }
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(Generated { files, warnings })
}

/// The file of `module`: `Notes/V1/NotesService.elm` for
/// `Notes.V1.NotesService`.
fn file(module: &elm::ast::Module) -> GeneratedFile {
    GeneratedFile {
        path: format!("{}.elm", module.name.as_str().replace('.', "/")),
        content: elm::print::print_module(module),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_sentinel_names_the_major_and_minor_version() {
        let mut parts = VERSION.split('.');
        let (major, minor) = (parts.next().unwrap(), parts.next().unwrap());
        assert_eq!(SENTINEL, format!("v{major}_{minor}"));
        let digits = |s: &str| !s.is_empty() && s.bytes().all(|b| b.is_ascii_digit());
        let (v_major, v_minor) = SENTINEL[1..].split_once('_').expect("v{major}_{minor}");
        assert!(SENTINEL.starts_with('v') && digits(v_major) && digits(v_minor));
        assert_eq!(HEADER_VERSION_PLACEHOLDER, format!("{major}.{minor}.X"));
    }
}
