//! What the corpus test, the route test and the plugin's corpus replay
//! (`crates/protoc-gen-elm-connect/tests/plugin.rs`, which includes this
//! file by path) share. Each uses part of it.
#![allow(dead_code)]

use std::fs;
use std::io::ErrorKind;
use std::path::{Path, PathBuf};

use elm_connect_gen::diagnostics::Diagnostics;
use elm_connect_gen::{HEADER_PREFIX, HEADER_VERSION_PLACEHOLDER, Options, VERSION};

/// The file in `expected/` that makes a case a diagnostics case.
pub const DIAGNOSTICS: &str = "diagnostics.txt";
/// The file in `expected/` beside the modules that pins the warnings a
/// successful run reports.
pub const WARNINGS: &str = "warnings.txt";
/// The optional file in a case that sets the generator's options.
pub const OPTIONS: &str = "options.txt";

/// `content` with the generator's version on its header line, the first,
/// replaced by [`HEADER_VERSION_PLACEHOLDER`]: `-- Generated by
/// elm-connect 0.1.X from ...`. The version is provenance in real output;
/// in committed expected output its patch would make every patch release
/// rewrite every file.
pub fn placeholder_header(content: &str) -> String {
    let real = format!("-- {HEADER_PREFIX}{VERSION} ");
    match content.strip_prefix(&real) {
        Some(rest) => format!("-- {HEADER_PREFIX}{HEADER_VERSION_PLACEHOLDER} {rest}"),
        None => content.to_owned(),
    }
}

pub fn repo_root() -> PathBuf {
    // Every crate sits at `crates/<name>`.
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// Every case directory of the corpus, sorted by name.
pub fn cases() -> Vec<PathBuf> {
    let root = repo_root().join("conformance/cases");
    let mut cases: Vec<PathBuf> = fs::read_dir(&root)
        .unwrap_or_else(|e| panic!("read {}: {e}", root.display()))
        .map(|entry| entry.expect("read a case").path())
        .filter(|path| path.is_dir())
        .collect();
    cases.sort();
    assert!(!cases.is_empty(), "no cases under {}", root.display());
    cases
}

pub fn case_name(case: &Path) -> String {
    case.file_name()
        .expect("a case has a name")
        .to_string_lossy()
        .into_owned()
}

pub fn is_diagnostics_case(case: &Path) -> bool {
    case.join("expected").join(DIAGNOSTICS).is_file()
}

/// Every file under `dir`, as `/`-separated paths relative to it, sorted.
pub fn files_under(dir: &Path) -> Vec<String> {
    fn walk(root: &Path, dir: &Path, out: &mut Vec<String>) {
        let Ok(entries) = fs::read_dir(dir) else {
            return;
        };
        for entry in entries {
            let path = entry.expect("read a directory entry").path();
            if path.is_dir() {
                walk(root, &path, out);
            } else {
                let relative = path.strip_prefix(root).expect("under the root");
                let parts: Vec<_> = relative
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy().into_owned())
                    .collect();
                out.push(parts.join("/"));
            }
        }
    }
    let mut out = Vec::new();
    walk(dir, dir, &mut out);
    out.sort();
    out
}

/// The `.proto` files under `dir`, as [`files_under`] names them.
pub fn protos(dir: &Path) -> Vec<String> {
    files_under(dir)
        .into_iter()
        .filter(|name| name.ends_with(".proto"))
        .collect()
}

/// The generator options of `case` as its optional `options.txt` writes
/// them, a protoc plugin parameter (`int64=int`) on one line; empty for
/// the defaults.
pub fn case_parameter(case: &Path) -> String {
    match fs::read_to_string(case.join(OPTIONS)) {
        Ok(text) => text.trim().to_owned(),
        Err(e) if e.kind() == ErrorKind::NotFound => String::new(),
        Err(e) => panic!("read {}: {e}", case.join(OPTIONS).display()),
    }
}

/// The generator options of `case` ([`case_parameter`]), or the problems
/// in its parameter.
pub fn case_options(case: &Path) -> Result<Options, Diagnostics> {
    Options::from_parameter(&case_parameter(case))
}

/// A case's input compiled with protox, imports included: the compiler,
/// the input protos, every one requested, and the include paths, `input/`
/// and the optional `include/` (protos the input may import, not
/// requested). It resolves as both entry points do, the embedded
/// googleapis files last.
pub struct Compiled {
    pub compiler: protox::Compiler,
    pub names: Vec<String>,
    pub include_paths: Vec<PathBuf>,
}

pub fn compile_case(case: &Path) -> Compiled {
    let input = case.join("input");
    let include = case.join("include");
    let names = protos(&input);
    assert!(!names.is_empty(), "{} has no input protos", input.display());
    let mut include_paths = vec![input.clone()];
    if include.is_dir() {
        include_paths.push(include);
    }
    let mut compiler = protox::Compiler::with_file_resolver(elm_connect_gen::googleapis::resolver(
        include_paths.clone(),
    ));
    compiler.include_source_info(true).include_imports(true);
    compiler
        .open_files(&names)
        .unwrap_or_else(|e| panic!("{} does not compile: {e:?}", input.display()));
    Compiled {
        compiler,
        names,
        include_paths,
    }
}
